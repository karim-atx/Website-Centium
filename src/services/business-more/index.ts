/**
 * The console's business row (the owned one, or since B7 the business this
 * account works for, services/business-console), or null when it has none.
 */
export async function fetchBusinessFull(userId: string): Promise<Result<BusinessFull | null>> {
  const access = await loadConsoleAccess(userId);
  if (!access.ok) return { ok: false, message: "Couldn't load your profile." };
  const id = access.value.current?.businessId;
  if (!id) return { ok: true, value: null };
  const { data, error } = await db.from("business_profiles").select(BUSINESS_COLUMNS).eq("id", id).maybeSingle();
  if (error) {
    console.error("[business-more] Could not read the business:", error.message);
    return fail(error, "Couldn't load your profile.");
  }
  return { ok: true, value: data ? toBusiness(data as BusinessRow) : null };
}

/** What the Business Profile sheets may change (all in the UPDATE grant). */
export interface BusinessPatch {
  name?: string;
  type?: BusinessTypeValue;
  bio?: string | null;
  /** The free-text area shown next to the name (storefront, Explore seller line, listing strength). */
  location?: string | null;
  publicPhone?: string | null;
  publicEmail?: string | null;
  publicWebsite?: string | null;
  instagram?: string | null;
  categories?: string[];
  active?: boolean;
}

/** Fired after the business type is saved, so the business navbar re-reads it. */
export const BUSINESS_TYPE_CHANGED_EVENT = "centium:business-type-changed";

const clean = (v: string | null | undefined) => (v?.trim() ? v.trim() : null);

/** Built from the keys actually present, so nothing another surface owns is overwritten. */
export function businessPatchRow(patch: BusinessPatch): Record<string, unknown> {
  const row: Record<string, unknown> = {};
  if ("name" in patch && patch.name !== undefined) row.business_name = patch.name.trim();
  if ("type" in patch && patch.type !== undefined) row.business_type = patch.type;
  if ("bio" in patch) row.bio = clean(patch.bio);
  if ("location" in patch) row.location = clean(patch.location);
  if ("publicPhone" in patch) row.public_phone = clean(patch.publicPhone);
  if ("publicEmail" in patch) row.public_email = clean(patch.publicEmail);
  if ("publicWebsite" in patch) row.public_website = clean(patch.publicWebsite);
  if ("instagram" in patch) row.instagram = clean(patch.instagram?.replace(/^@/, ""));
  if ("categories" in patch && patch.categories) row.categories = patch.categories;
  if ("active" in patch && patch.active !== undefined) row.active = patch.active;
  return row;
}

export async function saveBusiness(businessId: string, patch: BusinessPatch): Promise<Result<BusinessFull>> {
  // Round C Release 2: contact details belong in messages, said at save time.
  const contact = contactRefusal(patch.bio);
  if (contact) return { ok: false, message: contact };
  const row = businessPatchRow(patch);
  const { data, error } = await db.from("business_profiles").update(row).eq("id", businessId).select(BUSINESS_COLUMNS);
  if (error) {
    console.error("[business-more] Could not save the business:", error.message);
    if (error.code === "23514") return { ok: false, code: error.code, message: "One of these values isn't allowed. Check it and try again." };
    return fail(error, "Couldn't save. Try again.");
  }
  if (!data || data.length === 0) return { ok: false, code: "42501", message: "Couldn't save. Try again." };
  // The business navbar caches the type; tell it to read again after a type change.
  if ("type" in patch && patch.type !== undefined) {
    // Services build without the DOM lib, so the browser globals are reached loosely.
    const g = globalThis as unknown as { dispatchEvent?: (e: object) => boolean; Event?: new (type: string) => object };
    if (g.dispatchEvent && g.Event) g.dispatchEvent(new g.Event(BUSINESS_TYPE_CHANGED_EVENT));
  }
  return { ok: true, value: toBusiness(data[0] as BusinessRow) };
}

