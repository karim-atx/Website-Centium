export async function updateLocation(gymId: string, d: LocationDraft, originalPhones: string[]): Promise<Result<null>> {
  // The first phone is the one this sheet edits; any others the venue console
  // keeps are carried over untouched.
  const phones = [...phonesOf(d.phone), ...originalPhones.slice(1)];
  const row: Record<string, unknown> = { name: d.name.trim(), location: d.address.trim(), public_phones: phones };
  if (d.lat !== null && d.lng !== null) {
    row.lat = d.lat;
    row.lng = d.lng;
  }
  const { data, error } = await db.from("gyms").update(row).eq("id", gymId).select("id");
  if (error) {
    if (error.code === "23514") return { ok: false, code: error.code, message: "Check the phone number and try again." };
    return fail(error, "Couldn't save the location. Try again.");
  }
  if (!data || data.length === 0) return { ok: false, code: "42501", message: "Couldn't save the location. Try again." };
  return { ok: true, value: null };
}

/**
 * B10 entry rules on one venue (gyms_update_insider: the Venues permission).
 * Clamped to the CHECK ranges (gyms_min_entry_age_range 16 to 21,
 * gyms_guest_passes_range 0 to 10), the same clamp onboarding uses.
 */
export async function updateEntryRules(gymId: string, v: EntryRules): Promise<Result<EntryRules>> {
  const row = {
    min_entry_age: Math.min(ENTRY_AGE_MAX, Math.max(ENTRY_AGE_MIN, Math.round(v.minEntryAge))),
    guest_passes_per_month: Math.min(GUEST_PASSES_MAX, Math.max(0, Math.round(v.guestPassesPerMonth))),
    front_desk_checkin: v.frontDeskCheckIn,
  };
  const { data, error } = await db.from("gyms").update(row).eq("id", gymId).select("id");
  if (error) return fail(error, "Couldn't save the entry rules. Try again.");
  if (!data || data.length === 0) return { ok: false, code: "42501", message: "You need the Venues permission to change this. Ask the owner." };
  return { ok: true, value: { minEntryAge: row.min_entry_age, guestPassesPerMonth: row.guest_passes_per_month, frontDeskCheckIn: row.front_desk_checkin } };
}

/** Upcoming classes at a venue in the next 30 days (the remove guard). */
export async function countUpcomingClasses(gymId: string): Promise<Result<number>> {
  const today = new Date();
  const until = new Date(today.getTime() + 30 * 86400000);
  const iso = (d: Date) => d.toISOString().slice(0, 10);
  const { count, error } = await db
    .from("business_classes")
    .select("id", { count: "exact", head: true })
    .eq("gym_id", gymId)
    .gte("event_date", iso(today))
    .lte("event_date", iso(until));
  if (error) return fail(error, "Couldn't check this location's classes.");
  return { ok: true, value: count ?? 0 };
}

export async function removeLocation(gymId: string): Promise<Result<null>> {
  const { error } = await db.from("gyms").delete().eq("id", gymId);
  if (error) {
    console.error("[business-more] Could not remove the location:", error.message);
    if (error.code === "23503") return { ok: false, code: error.code, message: "Members still hold memberships here, so it can't be removed yet." };
    return fail(error, "Couldn't remove the location. Try again.");
  }
  return { ok: true, value: null };
}

