/** B11: business_store_settings is writable only with the `store` permission. */
const STORE_PERMISSION = "Changing store settings needs the Store permission.";

const STORE_COLUMNS =
  "sells_products, offers_appointments, delivery_enabled, pickup_enabled, delivery_fee, free_delivery_over, delivery_time_text, returns_policy, allow_exchanges";

const num = (v: unknown): number | null => (v === null || v === undefined || v === "" ? null : Number(v));

export async function fetchStoreSettings(businessId: string): Promise<Result<StoreSettings>> {
  const { data, error } = await db.from("business_store_settings").select(STORE_COLUMNS).eq("business_id", businessId).maybeSingle();
  if (error) return fail(error, "Couldn't load your policies.");
  const r = data as Record<string, unknown> | null;
  return {
    ok: true,
    value: {
      exists: !!r,
      sellsProducts: r ? !!r.sells_products : true,
      offersAppointments: r ? !!r.offers_appointments : false,
      deliveryEnabled: r ? !!r.delivery_enabled : false,
      pickupEnabled: r ? !!r.pickup_enabled : false,
      deliveryFee: num(r?.delivery_fee),
      freeDeliveryOver: num(r?.free_delivery_over),
      deliveryTimeText: (r?.delivery_time_text as string | null) ?? null,
      returnsPolicy: (r?.returns_policy as string | null) ?? null,
      allowExchanges: r ? !!r.allow_exchanges : false,
    },
  };
}

/**
 * Saves the whole settings row. The table's rules are checked here first so
 * the person reads a sentence, not a constraint name: delivery terms only
 * while delivery is on, exchanges only with a returns policy, and the row must
 * sell products or offer appointments.
 */
export async function saveStoreSettings(businessId: string, s: StoreSettings): Promise<Result<StoreSettings>> {
  const row = {
    sells_products: s.sellsProducts || !s.offersAppointments,
    offers_appointments: s.offersAppointments,
    delivery_enabled: s.deliveryEnabled,
    pickup_enabled: s.pickupEnabled,
    delivery_fee: s.deliveryEnabled ? s.deliveryFee : null,
    free_delivery_over: s.deliveryEnabled ? s.freeDeliveryOver : null,
    delivery_time_text: s.deliveryEnabled ? clean(s.deliveryTimeText) : null,
    returns_policy: clean(s.returnsPolicy),
    allow_exchanges: !!clean(s.returnsPolicy) && s.allowExchanges,
  };
  const res = s.exists
    ? await db.from("business_store_settings").update(row).eq("business_id", businessId).select(STORE_COLUMNS)
    : await db.from("business_store_settings").insert({ business_id: businessId, ...row }).select(STORE_COLUMNS);
  if (res.error) {
    console.error("[business-more] Could not save store settings:", res.error.message);
    // B11: only a seat with `store` may write (RLS 42501 on insert).
    if (res.error.code === "42501") return { ok: false, code: res.error.code, message: STORE_PERMISSION };
    return fail(res.error, "Couldn't save. Try again.");
  }
  // B11: an update RLS filters out changes nothing and says nothing; no row back = not allowed.
  if (s.exists && Array.isArray(res.data) && res.data.length === 0) return { ok: false, code: "42501", message: STORE_PERMISSION };
  const back = await fetchStoreSettings(businessId);
  return back;
}

