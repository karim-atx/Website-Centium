/* Atraxia website: the shared WebGL scene module (plain WebGL1, no library).
   Ported literally from the reference build's journey engine
   (source/index.r26.html, "Round 4: the journey", shaders 07-VS and 08-FS):
   one particle field in which every particle has a position in each of nine
   formations, blended by weights (uW0..uW8).

     0 galaxy echo   1 chaos (Philosophy)   2 swish strands (Philosophy)
     3 orbital system (Portfolio)   4 founders (Leadership)
     5 constellation (What guides us)   6 star map (Explorations)
     7 beacon (Reach out)   8 drifting field (footer)

   The landing page (journey.js, batch 3) drives all nine from scroll
   position. The Blog and article use a lighter build of the same engine
   (blog-scene.js): only the formations they show are compiled into the
   vertex shader. The particle data is generated by the same seeded generator
   in both cases, so the same particles land in the same places. */
